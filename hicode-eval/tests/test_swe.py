class SweExportTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.root=Path(self.tmp.name)
        self.base=self.root/'base';self.final=self.root/'final';self.base.mkdir();self.final.mkdir()
    def tearDown(self):self.tmp.cleanup()
    def test_patch_uses_actual_files_not_actor_git_and_captures_all_file_operations(self):
        (self.base/'edit.py').write_text('before\n');(self.final/'edit.py').write_text('after\n')
        (self.base/'deleted').write_text('old\n');(self.final/'added').write_text('new\n')
        (self.base/'binary').write_bytes(b'\x00old');(self.final/'binary').write_bytes(b'\x00new')
        (self.base/'exec').write_text('run\n');(self.final/'exec').write_text('run\n');(self.final/'exec').chmod(0o755)
        (self.final/'.git').mkdir();(self.final/'.git/config').write_text('[core]\n hooksPath = /tmp/bad\n')
        patch=export_patch(self.base,self.final)
        self.assertIn('GIT binary patch',patch);self.assertIn('new mode 100755',patch)
        self.assertIn('deleted file mode',patch);self.assertIn('new file mode',patch);self.assertNotIn('.git/config',patch)
        replay=self.root/'replay';shutil.copytree(self.base,replay)
        subprocess.run(['git','apply','--binary','-'],cwd=replay,input=patch.encode(),check=True)
        self.assertEqual((replay/'binary').read_bytes(),b'\x00new');self.assertFalse((replay/'deleted').exists())
        self.assertEqual((replay/'added').read_text(),'new\n')
    def test_external_symlink_becomes_link_blob_without_reading_target(self):
        (self.final/'link').symlink_to('/etc/passwd')
        patch=export_patch(self.base,self.final)
        self.assertIn('120000',patch);self.assertIn('+/etc/passwd',patch);self.assertNotIn('root:',patch)

    def test_new_runtime_caches_are_omitted_without_trusting_actor_ignore_rules(self):
        (self.final/'.gitignore').write_text('*\n')
        (self.final/'new.py').write_text('real source\n')
        (self.final/'__pycache__').mkdir()
        (self.final/'__pycache__/new.cpython-39.pyc').write_bytes(b'generated bytecode')
        (self.final/'__pycache__/fixture.py').write_text('keep new source\n')
        cache=self.final/'.pytest_cache';cache.mkdir()
        (cache/'CACHEDIR.TAG').write_text('Signature: 8a477f597d28d172789f06886806bc55\n')
        (cache/'nodeids').write_text('runtime test IDs\n')
        patch=export_patch(self.base,self.final)
        self.assertIn('new.py',patch);self.assertIn('__pycache__/fixture.py',patch)
        self.assertNotIn('new.cpython-39.pyc',patch);self.assertNotIn('.pytest_cache',patch)
        self.assertTrue((cache/'nodeids').exists())  # Complete evidence is untouched.

    def test_frozen_ignore_rules_exclude_new_build_outputs_with_non_utf8_bytes(self):
        (self.base/'.gitignore').write_text('build/\nresult_images/\n')
        (self.final/'.gitignore').write_text('*\n')
        (self.final/'solution.py').write_text('fixed = True\n')
        for name in ('build','result_images'):
            directory=self.final/name;directory.mkdir()
            (directory/'generated.txt').write_bytes(b'generated \xfc\n')
        patch=export_patch(self.base,self.final)
        self.assertIn('solution.py',patch)
        self.assertIn('.gitignore',patch)
        self.assertNotIn('generated.txt',patch)
        self.assertTrue((self.final/'build/generated.txt').exists())

    def test_preexisting_cache_named_fixtures_and_new_unrecognized_directories_are_preserved(self):
        for root in [self.base,self.final]:
            (root/'.gitignore').write_text('build/\n')
            (root/'build').mkdir();(root/'build/fixture.txt').write_text('original\n')
        (self.final/'build/fixture.txt').write_text('changed\n')
        for root in [self.base,self.final]:
            (root/'__pycache__').mkdir();(root/'__pycache__/fixture.pyc').write_bytes(b'original')
        (self.final/'__pycache__/fixture.pyc').write_bytes(b'changed fixture')
        (self.final/'.pytest_cache').mkdir();(self.final/'.pytest_cache/source.py').write_text('source\n')
        patch=export_patch(self.base,self.final)
        self.assertIn('build/fixture.txt',patch)
        self.assertIn('__pycache__/fixture.pyc',patch);self.assertIn('.pytest_cache/source.py',patch)
    def test_special_files_and_symlink_repository_roots_rejected(self):
        os.mkfifo(self.final/'fifo')
        with self.assertRaisesRegex(ValueError,'Special'):export_patch(self.base,self.final)
        alias=self.root/'alias';alias.symlink_to(self.base)
        with self.assertRaisesRegex(ValueError,'root'):snapshot(alias,self.root/'out')
    def test_swe_namespace_has_testbed_and_attempt_local_python_without_hidden_tests(self):
        args=namespace_argv(['python','-V'],'/eval/project','/eval/home','/eval/logs','/run/control',workdir='/testbed',environment='/eval/swe-envs/task')
        self.assertNotIn('/tests',args);self.assertNotIn('/app',args)
        i=args.index('/eval/swe-envs/task');self.assertEqual(args[i+1],'/opt/hicode-swe/env')
        self.assertEqual(args[args.index('--chdir')+1],'/testbed')
    def test_pytest_uses_reviewed_local_build_backend_in_preflight_and_actor(self):
        self.assertEqual(editable_install_argv('/env/bin/python','/testbed','pytest-dev/pytest'),
                         ['/env/bin/python','-m','pip','install','--no-deps','--no-build-isolation','-e','/testbed'])
        self.assertIn('--no-build-isolation',editable_install_argv('/env/bin/python','/testbed','django/django'))
        from swe import namespace_eval_commands
        self.assertEqual(namespace_eval_commands(['python -m pip install -e .','pytest -rA xarray/tests/test_dataset.py'],
                                                'pydata/xarray','0.12'),
                         ['python -m pip install --no-deps --no-build-isolation -e .','pytest -rA xarray/tests/test_dataset.py'])

